const text = <E>(stream: Stream.Stream<Uint8Array, E>): Effect.Effect<string, E> =>
  Stream.mkString(Stream.decodeText(stream));

/** Runs `command` with `args` to the end and returns its exit code and output. Fails only if it can't be run. */
export const run = (
  spawner: Spawner,
  command: string,
  args: ReadonlyArray<string>,
  options: { readonly cwd?: string; readonly env?: Readonly<Record<string, string>>; readonly stdin?: string } = {},
): Effect.Effect<Output, StepFailed> =>
  Effect.scoped(
    Effect.gen(function* () {
      const handle = yield* spawner.spawn(
        ChildProcess.make(command, [...args], {
          cwd: options.cwd,
          env: { ...options.env },
          extendEnv: true,
          stdin: options.stdin === undefined ? "ignore" : Stream.encodeText(Stream.make(options.stdin)),
        }),
      );
      const [stdout, stderr, code] = yield* Effect.all([text(handle.stdout), text(handle.stderr), handle.exitCode], {
        concurrency: "unbounded",
      });
      return { code, stdout, stderr };
    }),
  ).pipe(Effect.mapError((error) => stepFailed(`couldn't run ${command}: ${error.message}`)));

const shellEnv = (extra: Readonly<Record<string, string>>, runToken: string): Record<string, string> => {
  const env: Record<string, string> = {};
  for (const [key, value] of Object.entries(process.env)) {
    if (
      key !== "ELECTRON_RUN_AS_NODE" &&
      key !== "T3_PATCHER_PREPULLED" &&
      key !== "VITEST_MAX_WORKERS" &&
      value !== undefined
    ) {
      env[key] = value;
    }
  }
  const merged: Record<string, string> = { ...env, ...extra };
  merged["GOMAXPROCS"] ??= "2";
  const previous = merged["BSTACK_RUN_IDS"]?.trim() ?? "";
  merged["BSTACK_RUN_IDS"] = previous === "" ? runToken : `${previous},${runToken}`;
  return merged;
};

/**
 * Supervises `/bin/sh -c <script>` on macOS and Linux (compatible with macOS system Python 3.9+):
 * - Lock-free `SIGINT`/`SIGTERM` deferral across spawn, lock-holding critical sections (`SafeLock`), and `finally`
 *   teardown so an arriving `SIGTERM` never deadlocks on a lock the main thread already holds.
 * - Pauses the child on a startup pipe requiring an explicit `'1'` byte (EOF exits 130) until `(pid, start_time)`
 *   tracking and `kqueue` (`KQ_NOTE_FORK | KQ_NOTE_EXIT`, macOS) / `/proc` polling + `PR_SET_CHILD_SUBREAPER` (Linux)
 *   are armed, then `execv`s `/bin/sh`.
 * - macOS XNU boundary: unprivileged `KQ_NOTE_TRACK` returns `ENOTSUP`, XNU redacts `KERN_PROCARGS2` environment
 *   variables on SIP-protected system binaries (`/bin/*`, `/usr/bin/*`), and `responsibility_spawnattrs_setdisclaim`
 *   breaks Electron/Chromium Mach port rendezvous. Non-SIP binaries (`node`, `pnpm`, `Electron`, `Chromium`,
 *   `chrome_crashpad_handler`, `tsgo`, `esbuild`) retain `BSTACK_RUN_IDS` in `ps -E` across `setsid()` + `PPID = 1`.
 * - Validates effective backing directories (`cwd`, `$T3_PATCHER_ENV` parent, `$BSTACK_CACHE_DIR` / `config.toml`
 *   `cache_dir`, `$BSTACK_TOOLS_DIR`, `$BSTACK_WATCH_PATH`) before spawning and monitors their `st_dev` every 250ms,
 *   immediately `SIGKILL`ing the tree and recording `[volume-lost]` if an external volume unmounts or remounts.
 */
