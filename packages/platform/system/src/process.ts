const mintRunToken = Effect.fn("mintRunToken")(function* () {
  const parts: Array<string> = [String(process.pid)];
  for (let i = 0; i < 4; i += 1) {
    const word = yield* Random.nextIntBetween(0, 0x1_0000_0000, { halfOpen: true });
    parts.push(word.toString(16).padStart(8, "0"));
  }
  return parts.join("-");
});

type RunOutcome =
  | { readonly kind: "completed"; readonly code: number; readonly output: string }
  | { readonly kind: "leaked"; readonly summary: string }
  | { readonly kind: "volume-lost"; readonly summary: string };

/**
 * Runs `script` with /bin/sh in `folder`. Its output (stdout and stderr together) goes to `log` as it comes and is
 * returned with the exit code. Supervises the descendant tree from before the first fork (combining live `(pid, start)`
 * tracking with `BSTACK_RUN_IDS` lineage and a 250ms backing-volume `st_dev` watchdog) so every child and detached
 * daemon is reaped when the scope closes or a volume drops, and fails with `[no-concurrency-escapes]` if an exiting
 * step (`code === 0`) leaves live processes behind.
 */
export const runLogged = (
  spawner: Spawner,
  fs: FileSystem.FileSystem,
  input: {
    readonly folder: string;
    readonly script: string;
    readonly env: Readonly<Record<string, string>>;
    readonly log: string;
  },
): Effect.Effect<{ readonly code: number; readonly output: string }, StepFailed> =>
  Effect.scoped(
    Effect.gen(function* () {
      const token = yield* mintRunToken();
      const childEnv = shellEnv(input.env, token);
      const tempDir = yield* fs.makeTempDirectoryScoped({ prefix: "t3-run-" });
      const leakFile = `${tempDir}/leaked.txt`;
      const volFile = `${tempDir}/volume.txt`;
      const command =
        process.platform === "darwin" || process.platform === "linux"
          ? ChildProcess.make(
              "python3",
              ["-c", POSIX_SUPERVISOR, leakFile, volFile, token, input.script],
              {
                cwd: input.folder,
                env: childEnv,
                extendEnv: false,
                stdin: "ignore",
                detached: true,
                killSignal: "SIGTERM",
                forceKillAfter: "2 seconds",
              },
            )
          : ChildProcess.make("/bin/sh", ["-c", input.script], {
              cwd: input.folder,
              env: childEnv,
              extendEnv: false,
              stdin: "ignore",
            });
      const handle = yield* spawner.spawn(command);
      const kept: Array<string> = [];
      const drain = yield* handle.all.pipe(
        Stream.decodeText,
        Stream.tap((chunk) => Effect.sync(() => kept.push(chunk))),
        Stream.encodeText,
        Stream.run(fs.sink(input.log)),
        Effect.forkScoped,
      );
      const code = yield* handle.exitCode;
      yield* Fiber.join(drain).pipe(Effect.timeoutOption("2 seconds"));
      if (yield* fs.exists(volFile)) {
        const summary = (yield* fs.readFileString(volFile)).trim();
        if (summary !== "") {
          const volumeLost: RunOutcome = { kind: "volume-lost", summary };
          return volumeLost;
        }
      }
      if (code === 0 && (yield* fs.exists(leakFile))) {
        const summary = (yield* fs.readFileString(leakFile)).trim();
        if (summary !== "") {
          const leaked: RunOutcome = { kind: "leaked", summary };
          return leaked;
        }
      }
      const completed: RunOutcome = { kind: "completed", code, output: kept.join("") };
      return completed;
    }),
  ).pipe(
    Effect.mapError((error) => stepFailed(`couldn't run ${input.script}: ${error.message}`)),
    Effect.flatMap((outcome) => {
      switch (outcome.kind) {
        case "volume-lost":
          return Effect.fail(stepFailed(`[volume-lost] ${outcome.summary}`));
        case "leaked":
          return Effect.fail(stepFailed(`[no-concurrency-escapes] step left live process(es) running: ${outcome.summary}`));
        case "completed":
          return Effect.succeed({ code: outcome.code, output: outcome.output });
      }
    }),
  );

/** A StepFailed saying what couldn't be done, for `Effect.mapError`. */
export const couldnt = (what: string) => (): StepFailed => stepFailed(`couldn't ${what}`);
